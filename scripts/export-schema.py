#!/usr/bin/env python3
"""Build a portable fresh-database SQL install from the canonical migrations."""
from pathlib import Path
import re

root = Path(__file__).resolve().parent.parent
chunks = ["-- Generated by scripts/export-schema.py. Do not edit directly.\n"
          "-- PostgreSQL 17; fresh database only. No user data or credentials.\n"
          "-- On error, the transaction rolls back instead of replacing tables.\n"
          "\\set ON_ERROR_STOP on\nBEGIN;\n"
          "CREATE TABLE IF NOT EXISTS schema_migrations(version text PRIMARY KEY,applied_at timestamptz DEFAULT now());\n"]
for path in sorted((root / 'migrations').glob('*.up.sql')):
    version = path.name.removesuffix('.up.sql')
    if not re.fullmatch(r'[a-zA-Z0-9_]+', version):
        raise SystemExit('Unsafe migration filename')
    chunks.extend([f'\n-- Migration: {version}\n', path.read_text(),
                   f"\nINSERT INTO schema_migrations(version) VALUES('{version}');\n"])
chunks.append('\nCOMMIT;\n')
output = root / 'database/schema.sql'
output.parent.mkdir(exist_ok=True)
output.write_text(''.join(chunks))
print('Schema terbaru dibuat: database/schema.sql (tanpa data privat).')
